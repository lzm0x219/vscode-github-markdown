import githubMarkdownCss, {
  type GithubMarkdownCssOptions,
  type GithubMarkdownCssTheme
} from "generate-github-markdown-css";
import { createHash } from "node:crypto";
import { readFile, stat } from "node:fs/promises";
import { basename, join } from "node:path";
import { project } from "../shared/project";

export const githubThemes = [
  "light",
  "light_colorblind",
  "light_high_contrast",
  "light_tritanopia",
  "dark",
  "dark_colorblind",
  "dark_dimmed",
  "dark_high_contrast",
  "dark_tritanopia"
] as const satisfies readonly GithubMarkdownCssTheme[];

export type GithubTheme = (typeof githubThemes)[number];

export type CssAsset = {
  fileName: string;
  content: string;
};

export type GithubCssGenerator = (options: GithubMarkdownCssOptions) => Promise<string>;

export type GithubCssSnapshot = {
  schemaVersion: 1;
  capturedAt: string;
  extractor: {
    package: "generate-github-markdown-css";
    version: string;
    entryPage: string;
  };
  fixtureCommit: string;
  themes: readonly GithubTheme[];
  assets: readonly GithubCssSnapshotAsset[];
  filtering: GithubCssFilteringStats;
};

export type GithubCssSnapshotAsset = {
  url: string;
  sha256: string;
  etag?: string;
  lastModified?: string;
  cache: { freshness: "fresh" | "cached" | "unknown"; ageSeconds?: number };
  signals: GithubCssSignals;
};

export type GithubCssSignals = {
  mediaRules: number;
  dataSelectors: readonly string[];
  classSelectors: readonly string[];
};

export type GithubCssFilteringStats = {
  input: GithubCssSignals;
  output: GithubCssSignals;
  excluded: {
    mediaRules: number;
    dataSelectors: number;
    classSelectors: number;
  };
};

export type GithubCssSnapshotOptions = {
  fixtureCommit: string;
  generator?: GithubCssGenerator;
  githubToken?: string;
  capturedAt?: Date;
};

export class GithubCssSnapshotContractError extends Error {
  readonly category = "unsupported-css-asset-name";

  constructor(readonly assets: readonly GithubCssSnapshotAsset[]) {
    super(
      `GitHub CSS snapshot rejected an unsupported asset-name convention:\n${JSON.stringify(
        {
          conclusion: "extractor-input-contract-failed",
          category: "unsupported-css-asset-name",
          assets: assets.map(({ url, cache, signals }) => ({
            url,
            cache,
            signals: summarizeSignals(signals)
          }))
        },
        null,
        2
      )}`
    );
    this.name = "GithubCssSnapshotContractError";
  }
}

const markdownRoot = ".vscode-github-markdown";
const sharedCssFile = "github-markdown.css";
const generatedHeader = "/* Generated by `nub run build` or `nub run dev`. Do not edit. */";
export const parityOnlyCssMarker = "/* Parity-only GitHub page styles. */";
const githubCssEntryPage = "https://github.com/sindresorhus/generate-github-markdown-css";

export function githubCssFileNames(): string[] {
  return [sharedCssFile, ...githubThemes.map(themeFileName)];
}

export function githubCssImports(): string {
  return githubCssFileNames()
    .map((fileName) => `@import "./${fileName}";`)
    .join("\n");
}

export async function readGithubCssAssets(): Promise<CssAsset[]> {
  return parseGithubCssAssets(await readFile(project.paths.parityReferenceCss, "utf8"));
}

export function parseGithubCssAssets(referenceCss: string): CssAsset[] {
  const marker = `\n${parityOnlyCssMarker}\n`;
  const markerIndex = referenceCss.indexOf(marker);
  if (markerIndex < 0) {
    throw new Error("GitHub parity reference has no parity-only CSS marker");
  }

  const sections = referenceCss.slice(0, markerIndex).split(generatedHeader);
  const prefix = sections.shift();
  const fileNames = githubCssFileNames();
  if (prefix?.trim() || sections.length !== fileNames.length) {
    throw new Error(
      `GitHub parity reference has ${sections.length} build assets; expected ${fileNames.length}`
    );
  }

  return fileNames.map((fileName, index) => ({
    fileName,
    content: `${generatedHeader}${sections[index] ?? ""}`.trimEnd() + "\n"
  }));
}

export async function generateGithubCssAssets(
  generator: GithubCssGenerator = githubMarkdownCss,
  githubToken: string | undefined = process.env["GITHUB_TOKEN"]
): Promise<CssAsset[]> {
  return withAuthenticatedGitHubApi(githubToken, () => generateGithubCssAssetsWith(generator));
}

/**
 * Generates CSS through the existing extractor while recording its remote inputs.
 *
 * The recorder deliberately wraps rather than reimplements the extractor: a changed
 * upstream asset or selector policy therefore becomes reviewable before it changes the
 * committed offline fixture.
 */
export async function generateGithubCssSnapshot(
  options: GithubCssSnapshotOptions
): Promise<{ assets: CssAsset[]; snapshot: GithubCssSnapshot }> {
  const captures = new Map<string, GithubCssSnapshotAsset>();
  const originalFetch = globalThis.fetch;
  globalThis.fetch = captureGitHubCssFetch(originalFetch, captures);
  try {
    const assets = await generateGithubCssAssets(options.generator, options.githubToken);
    if (captures.size === 0) await captureCachedGitHubCssAssets(captures);
    const observedAssets = [...captures.values()].sort((left, right) =>
      left.url.localeCompare(right.url)
    );
    if (observedAssets.length === 0) {
      throw new Error("GitHub CSS snapshot did not observe any CSS assets from the extractor");
    }

    const malformedAssets = observedAssets.filter(({ url }) => !hasStableGithubCssAssetName(url));
    if (malformedAssets.length > 0) {
      throw new GithubCssSnapshotContractError(malformedAssets);
    }

    const input = combineSignals(observedAssets.map(({ signals }) => signals));
    const output = inspectGithubCssSignals(assets.map(({ content }) => content).join("\n"));
    return {
      assets,
      snapshot: {
        schemaVersion: 1,
        capturedAt: (options.capturedAt ?? new Date()).toISOString(),
        extractor: {
          package: "generate-github-markdown-css",
          version: await readGithubCssExtractorVersion(),
          entryPage: githubCssEntryPage
        },
        fixtureCommit: options.fixtureCommit,
        themes: githubThemes,
        assets: observedAssets,
        filtering: {
          input,
          output,
          excluded: {
            mediaRules: Math.max(0, input.mediaRules - output.mediaRules),
            dataSelectors: countDifference(input.dataSelectors, output.dataSelectors),
            classSelectors: countDifference(input.classSelectors, output.classSelectors)
          }
        }
      }
    };
  } finally {
    globalThis.fetch = originalFetch;
  }
}

export function inspectGithubCssSignals(css: string): GithubCssSignals {
  return {
    mediaRules: [...css.matchAll(/@media\b/gi)].length,
    dataSelectors: uniqueMatches(css, /\[\s*(data-[\w-]+)/gi),
    classSelectors: uniqueMatches(css, /\.([_a-z][\w-]*)/gi)
  };
}

async function generateGithubCssAssetsWith(generator: GithubCssGenerator): Promise<CssAsset[]> {
  const markdownStyles = await generator({ onlyStyles: true, rootSelector: markdownRoot });
  const themeResults: Array<{
    theme: GithubTheme;
    sharedVariables: string;
    themeVariables: string;
  }> = [];
  for (const theme of githubThemes) {
    themeResults.push(await generateThemeVariables(theme, generator));
  }

  if (markdownStyles.includes("[data-theme=")) {
    throw new Error("Generated GitHub Markdown styles unexpectedly contain theme selectors");
  }

  const sharedVariables = themeResults[0]?.sharedVariables;
  if (!sharedVariables) throw new Error("Generated GitHub CSS has no shared variables");
  for (const result of themeResults) {
    if (result.sharedVariables !== sharedVariables) {
      throw new Error(`Generated shared variables differ for theme ${result.theme}`);
    }
  }

  return [
    {
      fileName: sharedCssFile,
      content: generatedCss(`${sharedVariables}\n\n${markdownStyles}`)
    },
    ...themeResults.map(({ theme, themeVariables }) => ({
      fileName: themeFileName(theme),
      content: generatedCss(renderThemeCss(theme, themeVariables))
    }))
  ];
}

async function withAuthenticatedGitHubApi<T>(
  token: string | undefined,
  operation: () => Promise<T>
): Promise<T> {
  if (!token) {
    return operation();
  }

  const originalFetch = globalThis.fetch;
  const authenticatedFetch: typeof fetch = (input, init) => {
    const requestUrl = new URL(input instanceof Request ? input.url : input);
    if (requestUrl.origin !== "https://api.github.com") {
      return originalFetch(input, init);
    }

    const headers = new Headers(input instanceof Request ? input.headers : undefined);
    new Headers(init?.headers).forEach((value, key) => headers.set(key, value));
    if (!headers.has("Authorization")) {
      headers.set("Authorization", `Bearer ${token}`);
    }
    return originalFetch(input, { ...init, headers });
  };

  globalThis.fetch = authenticatedFetch;
  try {
    return await operation();
  } finally {
    globalThis.fetch = originalFetch;
  }
}

export function splitThemeCss(
  css: string,
  theme: GithubTheme
): { sharedVariables: string; themeVariables: string } {
  const selector = `${markdownRoot},\n[data-theme="${theme}"] {\n`;
  const selectorStart = css.indexOf(selector);
  const blockEnd = css.lastIndexOf("\n}");
  if (selectorStart < 0 || blockEnd <= selectorStart) {
    throw new Error(`Cannot split generated CSS variables for theme ${theme}`);
  }
  return {
    sharedVariables: css.slice(0, selectorStart).trim(),
    themeVariables: css.slice(selectorStart + selector.length, blockEnd)
  };
}

export function renderThemeCss(theme: GithubTheme, variables: string): string {
  return [
    `${markdownRoot}[data-color-mode="light"][data-light-theme="${theme}"],
${markdownRoot}[data-color-mode="dark"][data-dark-theme="${theme}"] {
${variables}
}`,
    `body.vscode-light ${markdownRoot}[data-color-mode="auto"][data-light-theme="${theme}"],
body.vscode-high-contrast-light ${markdownRoot}[data-color-mode="auto"][data-light-theme="${theme}"] {
${indent(variables)}
}`,
    `body.vscode-dark ${markdownRoot}[data-color-mode="auto"][data-dark-theme="${theme}"],
body.vscode-high-contrast ${markdownRoot}[data-color-mode="auto"][data-dark-theme="${theme}"] {
${indent(variables)}
}`
  ].join("\n\n");
}

async function generateThemeVariables(theme: GithubTheme, generator: GithubCssGenerator) {
  const css = await generator({
    light: theme,
    dark: theme,
    onlyVariables: true,
    useFixture: false,
    rootSelector: markdownRoot
  });
  return { theme, ...splitThemeCss(css, theme) };
}

function themeFileName(theme: GithubTheme): string {
  return `github-markdown-theme-${theme}.css`;
}

function indent(value: string): string {
  return value
    .split("\n")
    .map((line) => `  ${line}`)
    .join("\n");
}

function generatedCss(css: string): string {
  return `${generatedHeader}\n\n${css}\n`;
}

function captureGitHubCssFetch(
  fetcher: typeof fetch,
  captures: Map<string, GithubCssSnapshotAsset>
): typeof fetch {
  return async (input, init) => {
    const response = await fetcher(input, init);
    const url = fetchUrl(input);
    if (!url || !url.pathname.endsWith(".css") || !response.ok) return response;

    const content = await response.clone().text();
    const etag = response.headers.get("ETag");
    const lastModified = response.headers.get("Last-Modified");
    captures.set(url.href, {
      url: url.href,
      sha256: sha256(content),
      ...(etag ? { etag } : {}),
      ...(lastModified ? { lastModified } : {}),
      cache: cacheFreshness(response.headers.get("Age")),
      signals: inspectGithubCssSignals(content)
    });
    return response;
  };
}

function fetchUrl(input: RequestInfo | URL): URL | undefined {
  try {
    return new URL(input instanceof Request ? input.url : input);
  } catch {
    return undefined;
  }
}

function cacheFreshness(age: string | null): GithubCssSnapshotAsset["cache"] {
  if (age === null) return { freshness: "unknown" };
  const ageSeconds = Number(age);
  if (!Number.isInteger(ageSeconds) || ageSeconds < 0) return { freshness: "unknown" };
  return { freshness: ageSeconds === 0 ? "fresh" : "cached", ageSeconds };
}

async function captureCachedGitHubCssAssets(
  captures: Map<string, GithubCssSnapshotAsset>
): Promise<void> {
  const cacheDirectory = join(
    project.root,
    "node_modules",
    ".cache",
    "generate-github-markdown-css"
  );
  const entryPage = await readFile(
    join(cacheDirectory, `${basename(githubCssEntryPage)}.txt`),
    "utf8"
  );
  const urls = [...new Set(entryPage.match(/(?<=href=").+?\.css/g) ?? [])].sort((left, right) =>
    left.localeCompare(right)
  );
  for (const url of urls) {
    const cacheFile = join(cacheDirectory, `${basename(url)}.txt`);
    const [content, details] = await Promise.all([readFile(cacheFile, "utf8"), stat(cacheFile)]);
    captures.set(url, {
      url,
      sha256: sha256(content),
      cache: {
        freshness: "cached",
        ageSeconds: Math.max(0, Math.floor((Date.now() - details.mtimeMs) / 1_000))
      },
      signals: inspectGithubCssSignals(content)
    });
  }
}

function hasStableGithubCssAssetName(url: string): boolean {
  try {
    return /\/[-\w]+-\w+\.css$/i.test(new URL(url).pathname);
  } catch {
    return false;
  }
}

function combineSignals(signals: readonly GithubCssSignals[]): GithubCssSignals {
  return {
    mediaRules: signals.reduce((total, current) => total + current.mediaRules, 0),
    dataSelectors: [...new Set(signals.flatMap(({ dataSelectors }) => dataSelectors))].sort(
      (left, right) => left.localeCompare(right)
    ),
    classSelectors: [...new Set(signals.flatMap(({ classSelectors }) => classSelectors))].sort(
      (left, right) => left.localeCompare(right)
    )
  };
}

function summarizeSignals(signals: GithubCssSignals) {
  return {
    mediaRules: signals.mediaRules,
    dataSelectors: {
      count: signals.dataSelectors.length,
      sample: signals.dataSelectors.slice(0, 10)
    },
    classSelectors: {
      count: signals.classSelectors.length,
      sample: signals.classSelectors.slice(0, 10)
    }
  };
}

function uniqueMatches(css: string, pattern: RegExp): string[] {
  return [
    ...new Set(
      [...css.matchAll(pattern)]
        .map((match) => match[1]?.toLowerCase())
        .filter((match): match is string => match !== undefined)
    )
  ].sort((left, right) => left.localeCompare(right));
}

function countDifference(source: readonly string[], output: readonly string[]): number {
  const outputSet = new Set(output);
  return source.filter((value) => !outputSet.has(value)).length;
}

async function readGithubCssExtractorVersion(): Promise<string> {
  const packageJson = JSON.parse(await readFile(project.paths.packageJson, "utf8")) as {
    devDependencies?: Record<string, unknown>;
  };
  const version = packageJson.devDependencies?.["generate-github-markdown-css"];
  if (typeof version !== "string" || !/^\d+\.\d+\.\d+$/.test(version)) {
    throw new Error("package.json has no exact generate-github-markdown-css version");
  }
  return version;
}

function sha256(value: string): string {
  return createHash("sha256").update(value).digest("hex");
}
